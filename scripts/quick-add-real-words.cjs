#!/usr/bin/env node
/**
 * Regenerates src/lib/quick-add/real-words.ts: real English/Spanish words that sit one
 * typo away from a word Quick add corrects towards, so typo-fixing never changes them
 * ("marker" is not a typo of "market", "marco" is not a typo of "marca").
 *
 * Uses the MIT-licensed word lists by Zeke Sikelianos at development time only;
 * the lists themselves are not shipped. Run after changing the vocabulary:
 *
 *   npx --yes -p an-array-of-english-words@2.0.0 -p an-array-of-spanish-words@2.0.0 \
 *     node scripts/quick-add-real-words.cjs
 *   (or pass the two index.json paths as arguments)
 */
const fs = require('node:fs')
const path = require('node:path')
const { load } = require('../tests/load-ts.cjs')

process.chdir(path.join(__dirname, '..'))
const vocabulary = load('src/lib/quick-add/vocabulary.ts')
const fuzzy = load('src/lib/quick-add/fuzzy.ts')

const lists = process.argv.slice(2).length
  ? process.argv.slice(2).map((file) => JSON.parse(fs.readFileSync(file, 'utf8')))
  : [require('an-array-of-english-words'), require('an-array-of-spanish-words')]

const fold = (w) => w.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
const targets = vocabulary.generalTypoTargets()
const targetSet = new Set(targets)
const byFirst = new Map()
for (const t of targets) byFirst.set(t[0], [...(byFirst.get(t[0]) ?? []), t])

const real = new Set()
let checked = 0
for (const list of lists) {
  for (const raw of list) {
    const w = fold(raw)
    if (w.length < 5 || !/^[a-z]+$/.test(w) || targetSet.has(w)) continue
    checked += 1
    if (fuzzy.closestGeneral(w, byFirst.get(w[0]) ?? [])) real.add(w)
  }
}

const words = Array.from(real).sort()
const out = `// GENERATED by scripts/quick-add-real-words.cjs — do not edit by hand.
// Real words one typo away from a Quick add correction target; typo-fixing leaves them alone.
// Derived from the MIT-licensed "an-array-of-english-words" / "an-array-of-spanish-words" (Zeke Sikelianos).
// ${words.length} words, from ${checked} checked against ${targets.length} targets.

export const REAL_WORD_NEIGHBOURS: ReadonlySet<string> = new Set(
  ${JSON.stringify(words.join(' '))}.split(' '),
)
`
fs.writeFileSync('src/lib/quick-add/real-words.ts', out)
console.log(`real-words.ts: ${words.length} protected words (${checked} checked, ${targets.length} targets)`)
