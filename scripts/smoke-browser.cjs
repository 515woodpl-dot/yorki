// Run after npm run build. Uses an isolated DB and local port; never the live site.
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { spawn } = require('node:child_process')
const { chromium } = require('playwright')
const Database = require('better-sqlite3')
const bcrypt = require('bcryptjs')
const assert = require('node:assert/strict')

async function main() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'yorki-browser-'))
  const dbPath = path.join(dir, 'yorki.db')
  const port = process.env.TEST_PORT || '3100'
  const base = `http://127.0.0.1:${port}/task`
  const server = spawn(process.execPath, ['node_modules/next/dist/bin/next', 'start', '-H', '127.0.0.1', '-p', port], {
    env: { ...process.env, NODE_ENV: 'production', YORKI_DB_PATH: dbPath }, stdio: ['ignore', 'pipe', 'pipe'],
  })
  let logs = ''
  server.stdout.on('data', chunk => { logs += chunk })
  server.stderr.on('data', chunk => { logs += chunk })
  let browser
  try {
    let ready = false
    for (let i = 0; i < 80; i++) {
      if (server.exitCode !== null) throw new Error(logs)
      try { if ((await fetch(`${base}/api/health`)).ok) { ready = true; break } } catch {}
      await new Promise(resolve => setTimeout(resolve, 250))
    }
    assert.ok(ready, logs)
    const health = await fetch(`${base}/api/health`)
    assert.equal(health.headers.get('cache-control'), 'no-store')
    assert.deepEqual(Object.keys(await health.json()).sort(), ['status', 'time'])
    const db = new Database(dbPath)
    const now = new Date().toISOString()
    const expires = new Date(Date.now() + 3600000).toISOString()
    db.prepare('UPDATE users SET email = ?, password_hash = ? WHERE id = ?')
      .run('admin@example.com', bcrypt.hashSync('Test-password-1234', 12), '11111111-1111-1111-1111-111111111111')
    db.prepare('UPDATE users SET email = ? WHERE id = ?').run('staff@example.com', '22222222-2222-2222-2222-222222222222')
    db.prepare('INSERT INTO sessions VALUES (?, ?, ?, ?)').run('staff-test-session', '22222222-2222-2222-2222-222222222222', now, expires)
    db.prepare('INSERT INTO comments VALUES (?, ?, ?, ?, ?, ?, ?, ?)')
      .run('private-note', 't-2', '11111111-1111-1111-1111-111111111111', 'SECRET-INTERNAL-NOTE', 1, now, now, null)
    const privateFile = path.join(dir, 'private.txt')
    fs.writeFileSync(privateFile, 'PRIVATE-ATTACHMENT')
    const insertAttachment = db.prepare('INSERT INTO attachments (id, task_id, uploaded_by, file_name, file_size, file_type, storage_path, public_url, created_at, deleted_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)')
    insertAttachment.run('admin-file', 't-1', '11111111-1111-1111-1111-111111111111', 'private.txt', 18, 'text/plain', privateFile, '/api/attachments/admin-file', now, null)
    insertAttachment.run('staff-file', 't-2', '11111111-1111-1111-1111-111111111111', 'private.txt', 18, 'text/plain', privateFile, '/api/attachments/staff-file', now, null)
    db.prepare("UPDATE tasks SET custom_fields = ? WHERE id = 't-1'").run(JSON.stringify({ share_token: 'test-public-share' }))
    browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || (fs.existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), headless: true, args: ['--no-sandbox'] })
    const anonymous = await browser.newContext({ serviceWorkers: 'block' })
    const page = await anonymous.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    for (const route of ['/dashboard', '/admin/users', '/archive', '/submit']) {
      const response = await fetch(base + route, { redirect: 'manual' })
      assert.equal(response.status, 307, route)
      assert.equal(response.headers.get('location'), '/task/login', route)
    }
    await page.goto(base + '/admin/users')
    await page.waitForURL('**/task/login')
    await page.locator('input[type=email]').fill('admin@example.com')
    await page.locator('input[type=password]').fill('Test-password-1234')
    await page.getByRole('button', { name: /sign in/i }).click()
    await page.waitForURL('**/task/dashboard')
    await page.getByText('Finalize Yorki board polish', { exact: true }).filter({ visible: true }).waitFor()
    // The Quick add box pushes the columns down: scroll them into view so the mouse can reach them.
    await page.getByRole('button', { name: 'Open task: Finalize Yorki board polish', exact: true }).filter({ visible: true }).scrollIntoViewIfNeeded()
    const sourceCard = await page.getByRole('button', { name: 'Open task: Finalize Yorki board polish', exact: true }).filter({ visible: true }).boundingBox()
    const targetCard = await page.getByRole('button', { name: 'Open task: Clarify mobile nav behavior', exact: true }).filter({ visible: true }).boundingBox()
    await page.mouse.move(sourceCard.x + sourceCard.width / 2, sourceCard.y + 30)
    await page.mouse.down()
    await page.mouse.move(sourceCard.x + sourceCard.width / 2 + 12, sourceCard.y + 35, { steps: 3 })
    await page.mouse.move(targetCard.x + targetCard.width / 2, targetCard.y + 60, { steps: 20 })
    await page.waitForTimeout(150)
    await page.mouse.up()
    for (let i = 0; i < 40 && db.prepare("SELECT column_id FROM tasks WHERE id = 't-1'").get().column_id !== 'c-pending'; i++) await page.waitForTimeout(100)
    assert.equal(db.prepare("SELECT column_id FROM tasks WHERE id = 't-1'").get().column_id, 'c-pending', 'drag must persist destination')
    db.prepare("UPDATE tasks SET column_id = 'c-inbox', status = 'new' WHERE id = 't-1'").run()
    await page.reload()
    await page.getByRole('combobox', { name: 'Filter by priority' }).click()
    await page.getByRole('option', { name: 'High' }).click()
    assert.equal(await page.getByRole('button', { name: 'Open task: Clarify mobile nav behavior', exact: true }).filter({ visible: true }).count(), 0)
    await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
    await page.getByRole('button', { name: 'List view', exact: true }).click()
    await page.getByText('Finalize Yorki board polish', { exact: true }).filter({ visible: true }).waitFor()
    await page.getByRole('button', { name: 'Calendar view', exact: true }).click()
    await page.getByRole('heading', { name: 'No due date', exact: false }).waitFor()
    await page.getByRole('button', { name: 'Board view', exact: true }).click()
    await page.getByLabel('Search tasks', { exact: true }).fill('NO-SUCH-TASK')
    await page.getByRole('heading', { name: 'No tasks match these filters' }).waitFor()
    await page.getByRole('button', { name: 'Clear filters', exact: true }).first().click()
    await page.getByRole('button', { name: 'Open task: Finalize Yorki board polish', exact: true }).filter({ visible: true }).focus()
    await page.keyboard.press('Enter')
    await page.waitForURL('**task=t-1')
    await page.getByRole('button', { name: 'Lock card' }).click()
    await page.getByRole('button', { name: 'Unlock card' }).waitFor()
    assert.equal(JSON.parse(db.prepare("SELECT custom_fields FROM tasks WHERE id = 't-1'").get().custom_fields).locked, true)
    assert.equal(await page.getByRole('button', { name: 'Edit', exact: true }).count(), 0)
    await page.locator('input[aria-label="Comment files"]').setInputFiles({ name: 'sample.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\nYorki test') })
    await page.getByText('sample.pdf', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await page.getByRole('link', { name: 'sample.pdf' }).waitFor({ timeout: 60000 })
    await page.getByRole('button', { name: 'Unlock card' }).click()
    await page.getByRole('button', { name: 'Lock card' }).waitFor()
    await page.getByRole('button', { name: 'Close panel' }).click()
    assert.equal((await anonymous.request.get(base + '/api/attachments/admin-file')).status(), 200)
    await page.goto(base + '/admin/users')
    await page.getByText('admin@example.com', { exact: true }).filter({ visible: true }).first().waitFor()
    assert.equal((await page.content()).includes('password_hash'), false)
    const staffContext = await browser.newContext({ serviceWorkers: 'block', viewport: { width: 390, height: 844 } })
    await staffContext.addCookies([{ name: 'yorki_session', value: 'staff-test-session', url: base }])
    const staffPage = await staffContext.newPage()
    staffPage.on('pageerror', error => errors.push(error.message))
    await staffPage.goto(base + '/dashboard')
    await staffPage.getByRole('button', { name: 'List view', exact: true }).click()
    await staffPage.getByText('Clarify mobile nav behavior', { exact: true }).filter({ visible: true }).waitFor()
    const staffHtml = await staffPage.content()
    assert.equal(staffHtml.includes('SECRET-INTERNAL-NOTE'), false)
    assert.equal(staffHtml.includes('Finalize Yorki board polish'), false)
    assert.equal((await staffContext.request.get(base + '/api/attachments/admin-file')).status(), 403)
    const fileResponse = await staffContext.request.get(base + '/api/attachments/staff-file')
    assert.equal(fileResponse.status(), 200)
    assert.equal(await fileResponse.text(), 'PRIVATE-ATTACHMENT')
    assert.ok(fileResponse.headers()['cache-control'].includes('no-store'))
    const upload = await staffContext.request.post(base + '/api/upload', { multipart: {
      task_id: 't-2', file: { name: 'staff.txt', mimeType: 'text/plain', buffer: Buffer.from('test-upload') },
    } })
    assert.equal(upload.status(), 200)
    const deniedUpload = await staffContext.request.post(base + '/api/upload', { multipart: {
      task_id: 't-1', file: { name: 'denied.txt', mimeType: 'text/plain', buffer: Buffer.from('denied') },
    } })
    assert.equal(deniedUpload.status(), 403)
    await staffPage.goto(base + '/admin/users')
    await staffPage.waitForURL('**/task/dashboard')
    db.prepare('UPDATE users SET is_active = 0 WHERE id = ?').run('22222222-2222-2222-2222-222222222222')
    await staffPage.goto(base + '/dashboard')
    await staffPage.waitForURL('**/task/login')
    if (process.env.SCREENSHOT_DIR) {
      const captures = path.resolve(process.env.SCREENSHOT_DIR)
      fs.mkdirSync(captures, { recursive: true })
      const adminId = '11111111-1111-1111-1111-111111111111'
      db.prepare("UPDATE settings SET value = ? WHERE key = 'theme'").run(JSON.stringify({ default_mode: 'light' }))
      db.prepare("UPDATE tasks SET title = 'Confirm kitchen measurements', description = 'Check island dimensions before templating.', due_date = ?, has_real_due_date = 1, assigned_to = ?, custom_fields = ? WHERE id = 't-1'")
        .run(new Date(Date.now()-86400000).toISOString().slice(0,10), adminId, JSON.stringify({ share_token: 'test-public-share', address: 'Oak Street kitchen', job_number: 'GS-1042', checklist: [{ label: 'Measure island', checked: false }, { label: 'Confirm overhang', checked: false }, { label: 'Upload photos', checked: false }] }))
      db.prepare("UPDATE tasks SET title = 'Approve Calacatta slab layout', due_date = ?, has_real_due_date = 1, assigned_to = ?, custom_fields = ? WHERE id = 't-2'")
        .run(new Date().toISOString().slice(0,10), adminId, JSON.stringify({ address: 'Pinecrest residence', job_number: 'GS-1046' }))
      db.prepare("UPDATE tasks SET title = 'Send final drawings', completed_at = ?, custom_fields = ? WHERE id = 't-3'").run(now, JSON.stringify({ address: 'Lakeview kitchen', job_number: 'GS-1038' }))
      db.prepare('INSERT INTO columns VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)').run('c-progress', '00000000-0000-0000-0000-000000000001', 'In progress', '#d99a37', 2500, 0, 0, now, now, null)
      for (const [id,name] of [['sample-luis','Luis Torres'],['sample-ana','Ana Reyes']]) db.prepare('INSERT INTO users (id,full_name,display_name,email,role,is_active,created_at,updated_at) VALUES (?,?,?,?,?,?,?,?)').run(id,name,name.split(' ')[0],id+'@example.com','staff',1,now,now)
      const sample = db.prepare('INSERT INTO tasks (id,board_id,column_id,title,description,priority,position,submitted_by,assigned_to,due_date,has_real_due_date,custom_fields,created_at,updated_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)')
      for (const [i,title,column,who,priority,days,address] of [
        [1,'Review shop drawings','c-inbox',adminId,'normal',2,'Maple Avenue kitchen'],
        [2,'Schedule countertop installation','c-pending','sample-ana','normal',1,'Riverbend kitchen'],
        [3,'Template bathroom vanity','c-progress','sample-luis','high',0,'Cedar Lane bathroom'],
        [4,'Polish island edges','c-progress','sample-luis','normal',3,'Birchwood kitchen'],
      ]) sample.run('sample-'+i,'00000000-0000-0000-0000-000000000001',column,title,null,priority,2000,adminId,who,new Date(Date.now()+days*86400000).toISOString().slice(0,10),1,JSON.stringify({ address, job_number: 'GS-'+(1047+i), checklist: [{ label: 'Prepare', checked: true },{ label: 'Review', checked: false }] }),now,now)
      await page.setViewportSize({ width: 1600, height: 1000 })
      await page.goto(base + '/dashboard?view=board')
      await page.getByText('Confirm kitchen measurements', { exact: true }).filter({ visible: true }).waitFor()
      await page.screenshot({ path: path.join(captures, 'yorki-desktop.png'), fullPage: true })
      const phone = await browser.newContext({ storageState: await anonymous.storageState(), serviceWorkers: 'block', viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 2 })
      const phonePage = await phone.newPage()
      await phonePage.goto(base + '/dashboard?scope=mine&view=list')
      await phonePage.getByText('Confirm kitchen measurements', { exact: true }).filter({ visible: true }).waitFor()
      await phonePage.screenshot({ path: path.join(captures, 'yorki-mobile.png'), fullPage: false })
      assert.equal(await phonePage.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'mobile page must not overflow horizontally')
      await phone.close()
    }
    await page.getByLabel('Account menu', { exact: true }).filter({ visible: true }).click()
    await page.getByRole('button', { name: 'Sign out', exact: true }).filter({ visible: true }).click()
    await page.waitForURL('**/task/login')
    await page.goto(base + '/dashboard')
    await page.waitForURL('**/task/login')
    assert.equal((await anonymous.request.get(base + '/api/attachments/admin-file')).status(), 403)
    assert.equal((await anonymous.request.get(base + '/api/attachments/admin-file?token=test-public-share')).status(), 200)
    assert.deepEqual(errors, [])
    db.close()
    console.log('Browser smoke passed: anonymous guards, admin login/users, mobile staff visibility, internal notes, attachments/uploads/sharing, deactivation, logout; no page errors.')
  } catch (err) {
    console.error(logs.slice(-3000))
    throw err
  } finally {
    if (browser) await browser.close()
    server.kill('SIGTERM')
    await new Promise(resolve => { if (server.exitCode !== null) resolve(); else server.once('exit', resolve) })
    fs.rmSync(dir, { recursive: true, force: true })
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
